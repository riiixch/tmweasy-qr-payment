/**
 * Options to configure request retry behavior
 */
export interface RetryOptions {
  /** Maximum number of retry attempts. Defaults to 0 (no retries). */
  retries?: number;
  /** Initial delay before the first retry in milliseconds. Defaults to 1000. */
  minTimeout?: number;
  /** The multiplier factor to increase retry delay (exponential backoff). Defaults to 2. */
  factor?: number;
}

